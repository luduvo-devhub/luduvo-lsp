constexpr const char* marker = "-- Generated by Luduvo LSP; project ";
std::map<std::string, std::set<std::string>> groupedFields(const std::vector<FieldObservation>& observations)
{
    std::map<std::string, std::set<std::string>> result;
    for (const auto& observation : observations)
        result[observation.field.name].insert(observation.field.type);
    return result;
}
std::string recordType(const std::map<std::string, std::set<std::string>>& fields)
{
    std::string result = "{\n";
    for (const auto& field : fields)
    {
        result += "    [" + quoteSchemaString(field.first) + "]: ";
        bool first = true;
        for (const auto& type : field.second)
        {
            if (!first)
                result += " | ";
            result += type;
            first = false;
        }
        result += ",\n";
    }
    return result + "}";
}
bool overlayReference(const ContextStore& store, const std::string& projectId)
{
    std::error_code error;
    const auto directory = std::filesystem::u8path(store.directory()) / "schema-clients";
    std::filesystem::directory_iterator it(directory, error), end;
    bool active = false;
    for (; !error && it != end; it.increment(error))
    {
        if (!it->is_regular_file(error))
            continue;
        const auto source = readSharedFile(it->path().generic_u8string());
        if (!source)
            continue;
        try
        {
            const auto reference = nlohmann::json::parse(*source);
            if (!isProcessAlive({reference.at("pid").get<uint64_t>(), reference.at("start").get<uint64_t>()}))
            {
                std::filesystem::remove(it->path(), error);
                error.clear();
                continue;
            }
            if (reference.value("projectId", "") == projectId && reference.value("active", false))
                active = true;
        }
        catch (const std::exception&)
        {
        }
    }
    return active;
}

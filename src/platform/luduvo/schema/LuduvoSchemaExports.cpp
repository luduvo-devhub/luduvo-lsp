std::string quoteSchemaString(std::string_view value)
{
    std::string result = "\"";
    for (const unsigned char c : value)
    {
        if (c == '\\' || c == '"')
        {
            result += '\\';
            result += char(c);
        }
        else if (c < 32 || c == 127)
        {
            result += '\\';
            result += char('0' + c / 100);
            result += char('0' + c / 10 % 10);
            result += char('0' + c % 10);
        }
        else
            result += char(c);
    }
    return result + '"';
}
std::string generateProjectTypes(const ProjectSchemas& project)
{
    std::string output = std::string(marker) + project.projectId + "\n-- Saved project schemas. Changes are replaced automatically.\n--!strict\n\n";
    output += "type EventSchemas = {\n";
    for (const auto& name : eventSchemaNames(project))
        output += "[" + quoteSchemaString(name) + "]: " + recordType(groupedFields(eventSchemaFields(project, {name}))) + ",\n";
    output += "}\n\ntype EventKeys = {\n";
    for (const auto& name : eventSchemaNames(project))
    {
        std::string keys;
        if (hasCompleteEventSchema(project, {name}))
            for (const auto& field : groupedFields(eventSchemaFields(project, {name})))
                keys += (keys.empty() ? "" : " | ") + quoteSchemaString(field.first);
        else
            keys = "string";
        output += "[" + quoteSchemaString(name) + "]: " + (keys.empty() ? "never" : keys) + ",\n";
    }
    output += "}\n\ntype HandleSchemas = {\n";
    for (const auto& script : project.scripts)
    {
        const auto relative = std::filesystem::u8path(script.first).lexically_relative(std::filesystem::u8path(project.directory)).generic_u8string();
        output += "[" + quoteSchemaString(relative) + "]: " + recordType(groupedFields(handleSchemaFields(project, script.first))) + ",\n";
    }
    output += R"(}

type function eventFor(Name, Base, Column, Registry)
    local schemas: {type} = {}
    local function select(name: type): boolean
        if name:is("singleton") then
            local schema = Registry:readproperty(name)
            if not schema then return false end
            schemas[#schemas + 1] = schema
            return true
        elseif name:is("union") then
            for _, part in name:components() do
                if not select(part) then return false end
            end
            return true
        end
        return false
    end
    if not select(Name) or #schemas == 0 then return Base end
    local values: {[string]: {type}} = {}
    local counts: {[string]: number} = {}
    local keys: {[string]: type} = {}
    for _, schema in schemas do
        for key, property in schema:properties() do
            local name = key:value()
            local propertyType = property.read
            if type(name) == "string" and propertyType then
                if not values[name] then values[name], counts[name], keys[name] = {}, 0, key end
                local alternatives = values[name]
                alternatives[#alternatives + 1] = propertyType
                counts[name] += 1
            end
        end
    end
    local properties: {[type]: {read: type?, write: type?}} = {}
    for name, alternatives in values do
        local value = types.unionof(table.unpack(alternatives))
        local column = types.intersectionof(Column, types.newtable(nil, {
            index = types.number, readresult = value, writeresult = value,
        }))
        if counts[name] < #schemas then column = types.unionof(column, types.singleton(nil)) end
        properties[keys[name]] = {read = column}
    end
    return types.intersectionof(Base, types.newtable(properties))
end

type function handlesFor(Script, Base, Registry)
    if not Script:is("singleton") then return Base end
    local record = Registry:readproperty(Script)
    if not record then return Base end
    return types.intersectionof(Base, record)
end

type function eventKeys(Name, Registry)
    if Name:is("singleton") then return Registry:readproperty(Name) or types.string end
    if Name:is("union") then
        local keys: {type} = {}
        for _, part in Name:components() do keys[#keys + 1] = eventKeys(part, Registry) end
        return types.unionof(table.unpack(keys))
    end
    return types.string
end

export type EventTableKeys<Name> = eventKeys<Name, EventKeys>
export type EventTableFor<Name, Base = EventTable, Column = EventColumn> = eventFor<Name, Base, Column, EventSchemas>
export type HandlesFor<Script, Base = typeof(handles)> = handlesFor<Script, Base, HandleSchemas>

return {}
)";
    return output;
}
bool isGeneratedProjectTypes(std::string_view source, std::string_view projectId)
{
    auto header = source.substr(0, source.find('\n'));
    if (!header.empty() && header.back() == '\r')
        header.remove_suffix(1);
    const auto prefix = std::string(marker);
    return projectId.empty() ? header.size() > prefix.size() && header.substr(0, prefix.size()) == prefix : header == prefix + std::string(projectId);
}
void writeSchemaExportReference(const std::string& directory, const std::string& workspace, const std::string& projectId, bool active)
{
    const auto identity = currentProcessIdentity();
    if (!identity)
        return;
    const auto root = std::filesystem::u8path(directory) / "schema-clients";
    std::error_code error;
    std::filesystem::create_directories(root, error);
    if (error)
        return;
    const auto path = (root / (std::to_string(identity->processId) + "-" + schemaFingerprint(workspace + projectId) + ".json")).generic_u8string();
    if (!active)
    {
        std::filesystem::remove(std::filesystem::u8path(path), error);
        if (error)
            logging::write(logging::Level::Warning, "context.exports", "Could not release export reference: " + error.message());
        return;
    }
    const auto value =
        nlohmann::json{{"pid", identity->processId}, {"start", identity->startToken}, {"projectId", projectId}, {"active", active}}.dump();
    if (const auto previous = readSharedFile(path); previous && *previous == value)
        return;
    std::string failure;
    if (!writeFileAtomically(path, value, &failure))
        logging::write(logging::Level::Warning, "context.exports", "Could not update export reference: " + failure);
}
void updateSchemaDatabase(const ContextStore& store, const ClientLuduvoConfiguration& configuration)
{
    const auto catalog = store.load();
    if (!catalog)
        return;
    // These are derived records, not another source of project membership.
    // Forgetting a project must not leave an independently usable source index.
    std::error_code cacheError;
    const auto caches = std::filesystem::u8path(store.directory()) / "schemas";
    std::filesystem::directory_iterator cache(caches, cacheError), end;
    for (; !cacheError && cache != end; cache.increment(cacheError))
    {
        if (!cache->is_regular_file(cacheError))
            continue;
        const auto contents = readSharedFile(cache->path().generic_u8string());
        if (!contents)
            continue;
        try
        {
            const auto record = nlohmann::json::parse(*contents).get<ProjectSchemas>();
            if ((record.formatVersion >= 1 && record.formatVersion <= kSchemaIndexFormatVersion) && !catalog->projects.count(record.projectId) &&
                cache->path() == std::filesystem::u8path(schemaIndexPath(store.directory(), record.projectId)))
                std::filesystem::remove(cache->path(), cacheError);
        }
        catch (const nlohmann::json::exception&)
        {
        }
    }
    std::string core;
    if (const auto content = resolveActiveLuduvoContent(configuration))
        core = content->versionRoot;
    for (const auto& entry : catalog->projects)
    {
        const auto previous = loadProjectSchemas(store.directory(), entry.first);
        auto project = collectProjectSchemas(entry.second, store.loadWorld(entry.first), previous ? &*previous : nullptr, {}, core);
        bool active = overlayReference(store, entry.first);
        for (const auto& script : project.scripts)
            active = active || importsProjectTypes(script.second, project.exportPath);
        if (!active)
        {
            project.exportState = "not configured";
            project.exportError.clear();
        }
        else
        {
            const auto old = readSharedFile(project.exportPath);
            std::error_code statusError;
            const bool exists = std::filesystem::exists(std::filesystem::u8path(project.exportPath), statusError);
            const auto contents = generateProjectTypes(project);
            if (statusError || (exists && !old))
            {
                project.exportState = "failed";
                project.exportError = "Cannot safely read the existing export destination";
            }
            else if (old && !isGeneratedProjectTypes(*old, project.projectId))
            {
                project.exportState = "failed";
                project.exportError = "conflict: destination is not this project's generated module";
            }
            else
            {
                std::error_code error;
                std::filesystem::create_directories(std::filesystem::u8path(project.exportPath).parent_path(), error);
                std::string failure = error ? error.message() : "";
                if (!failure.empty() || ((!old || *old != contents) && !writeFileAtomically(project.exportPath, contents, &failure)))
                {
                    project.exportState = "failed";
                    project.exportError = failure;
                }
                else
                {
                    project.exportState = "up to date";
                    project.exportError.clear();
                    if (!old || *old != contents)
                    {
                        project.exportedAt = schemaTimeNow();
                        logging::write(logging::Level::Info, "context.exports", "Updated " + project.exportPath);
                    }
                }
            }
        }
        std::string error;
        if (!publishProjectSchemas(store.directory(), project, &error))
            logging::write(logging::Level::Warning, "context.schemas", "Could not publish schema index: " + error);
    }
}
